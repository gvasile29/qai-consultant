"""
QAI Consultant -- cross-document consistency helpers.

The Strategy and the Test Plan are generated by separate LLM calls, so left
alone they contradict the deterministic Effort report and the Risk Register
(different QA totals, re-rated risks, scrambled risk IDs, padded references).
This module holds the shared prompt blocks and the small, idempotent regex
post-processors that keep the documents aligned. Pure stdlib, no LLM.
"""

import re
from typing import Optional

# ── Effort numbers (Finding 3a) ────────────────────────────────────────────────

_EFFORT_FIELDS = (
    "pert_total_expected", "final_effort_min", "final_effort_max",
    "available_person_days", "capacity_gap", "qa_team_size", "project_duration_days",
)


def effort_facts(effort_data) -> Optional[dict]:
    """Extract the headline numbers from an EffortEstimator data object.
    Returns None for anything that is not a populated effort object
    (None, {}, a plain dict), so callers degrade to the old behaviour."""
    if effort_data is None or isinstance(effort_data, dict):
        return None
    facts = {name: getattr(effort_data, name, None) for name in _EFFORT_FIELDS}
    if not facts["pert_total_expected"]:
        return None
    return facts


def _n(value) -> str:
    return f"{float(value):g}"


def effort_prompt_block(facts: Optional[dict]) -> str:
    """Prompt block forcing the model to reuse the Effort report's numbers."""
    if not facts:
        return ""
    gap = facts["capacity_gap"] or 0
    gap_text = f"surplus of {_n(gap)}" if gap >= 0 else f"deficit of {_n(abs(gap))}"
    return f"""AUTHORITATIVE QA EFFORT (from the Effort Estimation report, computed deterministically):
- PERT expected QA effort: {_n(facts['pert_total_expected'])} person-days
- Final effort range: {_n(facts['final_effort_min'])} to {_n(facts['final_effort_max'])} person-days
- Available QA capacity: {_n(facts['available_person_days'])} person-days \
({facts['qa_team_size']} QA engineer(s) over about {facts['project_duration_days']} working days)
- Capacity gap: {gap_text} person-days
In "Resources & Man Power Estimation" use these numbers VERBATIM as the QA total. Do not invent
your own total, and do not invent per-activity day counts that you present as the QA total; if
you show a breakdown, express it as percentages of the {_n(facts['pert_total_expected'])} person-days
or omit it. State the capacity gap honestly.
"""


_NUM_DAYS_RE = re.compile(
    r"(\d+(?:\.\d+)?)(?=\s*\**\s*(?:person[- ]?days?|man[- ]?days?|pd\b|days?\b))", re.IGNORECASE
)
_SECTION_RE = re.compile(r"^##\s+(?:\d+\.\s*)?Resources", re.IGNORECASE | re.MULTILINE)
_NEXT_H2_RE = re.compile(r"^##\s", re.MULTILINE)


def enforce_effort_totals(text: str, facts: Optional[dict]) -> str:
    """In the Resources section, any line mentioning a 'total' whose day count
    differs from the Effort report is rewritten to the PERT expected effort.
    Idempotent; no-op without facts or without such a section."""
    if not facts or not text:
        return text
    start = _SECTION_RE.search(text)
    if not start:
        return text
    nxt = _NEXT_H2_RE.search(text, start.end())
    end = nxt.start() if nxt else len(text)
    allowed = {
        round(float(facts[k]), 1)
        for k in ("pert_total_expected", "final_effort_min", "final_effort_max", "available_person_days")
        if facts.get(k) is not None
    }
    allowed.add(round(abs(float(facts.get("capacity_gap") or 0)), 1))
    expected = _n(facts["pert_total_expected"])

    def fix(match: "re.Match") -> str:
        return match.group(1) if round(float(match.group(1)), 1) in allowed else expected

    lines = text[start.start():end].split("\n")
    for i, line in enumerate(lines):
        if "total" in line.lower():
            lines[i] = _NUM_DAYS_RE.sub(fix, line)
    return text[:start.start()] + "\n".join(lines) + text[end:]
