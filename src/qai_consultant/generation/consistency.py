"""
QAI Consultant -- cross-document consistency helpers.

The Strategy and the Test Plan are generated by separate LLM calls, so left
alone they contradict the deterministic Effort report and the Risk Register
(different QA totals, re-rated risks, scrambled risk IDs, padded references).
This module holds the shared prompt blocks and the small, idempotent regex
post-processors that keep the documents aligned. Pure stdlib, no LLM.
"""

import re
from typing import Optional

from qai_consultant.core.risk_ledger import parse_risk_matrix

# ── Effort numbers (Finding 3a) ────────────────────────────────────────────────

_EFFORT_FIELDS = (
    "pert_total_expected", "final_effort_min", "final_effort_max",
    "available_person_days", "capacity_gap", "qa_team_size", "project_duration_days",
)


def effort_facts(effort_data) -> Optional[dict]:
    """Extract the headline numbers from an EffortEstimator data object.
    Returns None for anything that is not a populated effort object
    (None, {}, a plain dict), so callers degrade to the old behaviour."""
    if effort_data is None or isinstance(effort_data, dict):
        return None
    facts = {name: getattr(effort_data, name, None) for name in _EFFORT_FIELDS}
    if not facts["pert_total_expected"]:
        return None
    return facts


def _n(value) -> str:
    return f"{float(value):g}"


def effort_prompt_block(facts: Optional[dict]) -> str:
    """Prompt block forcing the model to reuse the Effort report's numbers."""
    if not facts:
        return ""
    gap = facts["capacity_gap"] or 0
    gap_text = f"surplus of {_n(gap)}" if gap >= 0 else f"deficit of {_n(abs(gap))}"
    return f"""AUTHORITATIVE QA EFFORT (from the Effort Estimation report, computed deterministically):
- PERT expected QA effort: {_n(facts['pert_total_expected'])} person-days
- Final effort range: {_n(facts['final_effort_min'])} to {_n(facts['final_effort_max'])} person-days
- Available QA capacity: {_n(facts['available_person_days'])} person-days \
({facts['qa_team_size']} QA engineer(s) over about {facts['project_duration_days']} working days)
- Capacity gap: {gap_text} person-days
In "Resources & Man Power Estimation" use these numbers VERBATIM as the QA total. Do not invent
your own total, and do not invent per-activity day counts that you present as the QA total; if
you show a breakdown, express it as percentages of the {_n(facts['pert_total_expected'])} person-days
or omit it. State the capacity gap honestly.
"""


_NUM_DAYS_RE = re.compile(
    r"(\d+(?:\.\d+)?)(?=\s*\**\s*(?:person[- ]?days?|man[- ]?days?|pd\b|days?\b))", re.IGNORECASE
)
_SECTION_RE = re.compile(r"^##\s+(?:\d+\.\s*)?Resources", re.IGNORECASE | re.MULTILINE)
_NEXT_H2_RE = re.compile(r"^##\s", re.MULTILINE)


def enforce_effort_totals(text: str, facts: Optional[dict]) -> str:
    """In the Resources section, any line mentioning a 'total' whose day count
    differs from the Effort report is rewritten to the PERT expected effort.
    Idempotent; no-op without facts or without such a section."""
    if not facts or not text:
        return text
    start = _SECTION_RE.search(text)
    if not start:
        return text
    nxt = _NEXT_H2_RE.search(text, start.end())
    end = nxt.start() if nxt else len(text)
    allowed = {
        round(float(facts[k]), 1)
        for k in ("pert_total_expected", "final_effort_min", "final_effort_max", "available_person_days")
        if facts.get(k) is not None
    }
    allowed.add(round(abs(float(facts.get("capacity_gap") or 0)), 1))
    expected = _n(facts["pert_total_expected"])

    def fix(match: "re.Match") -> str:
        return match.group(1) if round(float(match.group(1)), 1) in allowed else expected

    lines = text[start.start():end].split("\n")
    for i, line in enumerate(lines):
        if "total" in line.lower():
            lines[i] = _NUM_DAYS_RE.sub(fix, line)
    return text[:start.start()] + "\n".join(lines) + text[end:]


# ── Risk ledger (Findings 3b, 7a) ──────────────────────────────────────────────

def risk_ledger(risk_register: str) -> list:
    """Parsed Risk Matrix rows ([] when absent or malformed; never raises)."""
    try:
        return parse_risk_matrix(risk_register or "")
    except Exception:  # defensive: the ledger is an enhancement, never a blocker
        return []


def ledger_rows_text(ledger: list) -> str:
    return "\n".join(
        f"{r['risk_id']} | {r['description']} | {r['likelihood']} | {r['impact']} | "
        f"{r['risk_level']} | {r['priority']}"
        for r in ledger
    )


def ledger_prompt_block(ledger: list) -> str:
    """Prompt block carrying the Risk Register's ratings; empty ledger -> ''."""
    if not ledger:
        return ""
    return f"""RISK LEDGER (authoritative, parsed from the Risk Register: ID | description | likelihood | impact | level | priority):
{ledger_rows_text(ledger)}
When the document discusses a risk from this ledger, reuse its ID and its likelihood, impact and
level VERBATIM. You may add detail and mitigations, but do NOT re-rate a risk or downgrade it
(for example, do not call a High/Critical integration risk Medium, and do not treat third-party
systems as "assumed reliable" when the ledger rates their failure as a risk). Any extra risk you
add that is not in the ledger must be labelled "additional (not in Risk Register)" with no R-number.
Never write an R-number (R08, R09, ...) that is not listed in the ledger above, not for an extra risk
and not for a requirement, regulation or clause.
"""


# ── Scope consistency (Finding 3c) ─────────────────────────────────────────────

SCOPE_RULES = """SCOPE CONSISTENCY RULES:
- Scope statements must be internally consistent: anything listed as out of scope or "not feasible"
  must not reappear later as a test type, activity, test item or feature to be tested.
- Do not assert or deny that the system has a user interface (UI, dashboard, web front end) unless the
  project context says so. If the intake does not say, write "UI not specified in the intake" and do not
  add UI test items or "No UI testing (backend-only)" exclusions.
"""

_SCOPE_HEADING_RE = re.compile(r"^##\s+\d+\.\s*Scope\b.*$", re.IGNORECASE | re.MULTILINE)
_SCOPE_MAX_CHARS = 1500


def extract_scope_decisions(strategy: str) -> str:
    """Short extract of the Strategy's in/out-of-scope sections ('' if none)."""
    if not strategy:
        return ""
    parts = []
    for m in _SCOPE_HEADING_RE.finditer(strategy):
        nxt = _NEXT_H2_RE.search(strategy, m.end())
        parts.append(strategy[m.start():nxt.start() if nxt else len(strategy)].strip())
    return "\n\n".join(parts)[:_SCOPE_MAX_CHARS]


# ── Test Plan ID mapping (Finding 7a) ──────────────────────────────────────────

PLAN_RISK_RULES = """RISK ID MAPPING RULES:
- Every "R0x" reference must match the RISK LEDGER above exactly: the ID, its description and its level.
  Never attach an R-number to a feature or test whose subject is a different risk in the ledger.
- Exit criteria must name every risk with level Critical in the ledger (not only some of them).
"""

_RISK_ID_RE = re.compile(r"\bR\d{2}\b")


def remove_unknown_risk_ids(text: str, ledger: list) -> str:
    """Remove 'Rnn' risk-ID mentions that are not in the ledger. No-op without a
    ledger. Idempotent. Deliberately does not judge whether a *known* ID suits
    the adjacent text."""
    ids = {r["risk_id"] for r in ledger or []}
    if not text or not ids or not all(_RISK_ID_RE.fullmatch(i) for i in ids):
        return text
    for unknown in sorted({m for m in _RISK_ID_RE.findall(text)} - ids):
        u = re.escape(unknown)
        text = re.sub(rf"\s*\(\s*{u}\s*\)", "", text)
        text = re.sub(rf"\b{u}\b\s*[,/&]\s*", "", text)
        text = re.sub(rf"\s*[,/&]\s*\b{u}\b", "", text)
        text = re.sub(rf"\s*\b{u}\b", "", text)
    return text


# ── Padding references (Finding 7b) ────────────────────────────────────────────

REFERENCES_RULES = """REFERENCES RULES:
- In the References section list only sources actually cited in the text as [Source N]. Do not add
  "(Implicit)" or "background" standards that the document does not cite.
"""

_REFS_HEADING_RE = re.compile(r"^#{2,3}\s+(?:\d+\.\s*)?References?\b.*$", re.IGNORECASE | re.MULTILINE)
_CITE_RE = re.compile(r"\[Source\s+(\d+)\]", re.IGNORECASE)


def drop_padding_references(text: str) -> str:
    """Drop References lines marked '(Implicit)' and lines whose [Source N]
    markers are all uncited in the body (only when the body cites something).
    Idempotent; unrelated text is untouched."""
    if not text:
        return text
    m = _REFS_HEADING_RE.search(text)
    if not m:
        return text
    nxt = _NEXT_H2_RE.search(text, m.end())
    end = nxt.start() if nxt else len(text)
    cited = set(_CITE_RE.findall(text[:m.start()] + text[end:]))
    kept = []
    for line in text[m.end():end].split("\n"):
        if "(implicit)" in line.lower():
            continue
        marks = set(_CITE_RE.findall(line))
        if marks and cited and not (marks & cited):
            continue
        kept.append(line)
    return text[:m.end()] + "\n".join(kept) + text[end:]


def strategy_prompt_kwargs(effort_data, risk_register: str) -> dict:
    """``build_strategy_prompt`` kwargs that tie the Strategy to the Effort
    report and Risk Register; empty when either is unusable, so callers
    degrade to the old behaviour."""
    kwargs: dict = {}
    facts = effort_facts(effort_data)
    if facts:
        kwargs["effort"] = facts
    ledger = risk_ledger(risk_register or "")
    if ledger:
        kwargs["ledger"] = ledger
    return kwargs


_ADDITIONAL_RISK_PREFIX = "ADD-"
# A standards body or regulation word earlier in the same clause ("UN R10", "ECE-R13",
# "ISO 26262 Part 2 R20", "CVSS R10"): a regulation or clause number, not a risk. Case-sensitive
# on purpose: lower-case "no"/"rule" are ordinary prose.
_STANDARDS_CONTEXT_RE = re.compile(r"\b(?:UN|UNECE|ECE|ISO|IEC|SAE|CVSS|NIST|Regulation)\b[^\n.;:]{0,30}$")
# A link target "](http://x/R10" and a code span "`R10`": renaming would change meaning.
_LINK_TARGET_RE = re.compile(r"\]\([^)\s]*$")


def relabel_unknown_risk_ids(text: str, ledger: list) -> str:
    """Rename 'Rnn' risk IDs that are not in the ledger to 'ADD-nn' so an extra risk
    the model invented cannot pass for a Risk Register entry. A pure token swap, so
    bold markers, bullets and table cells keep their shape (deleting the token, as
    remove_unknown_risk_ids does for the Test Plan, breaks prose). Best effort: leaves
    regulation numbers ('UN R10'), link targets, URL paths, anchors and code spans alone;
    a heading anchor written separately (`{#r10}`) is not kept in sync. No-op without a
    ledger; idempotent."""
    ids = {r["risk_id"] for r in ledger or []}
    if not text or not ids or not all(_RISK_ID_RE.fullmatch(i) for i in ids):
        return text

    def swap(match: "re.Match") -> str:
        if match.group(0) in ids:
            return match.group(0)
        prefix = text[text.rfind("\n", 0, match.start()) + 1:match.start()]
        if (
            prefix.endswith(("/", "#", "="))
            or prefix.count("`") % 2
            or _LINK_TARGET_RE.search(prefix)
            or _STANDARDS_CONTEXT_RE.search(prefix[-60:])
        ):
            return match.group(0)
        return _ADDITIONAL_RISK_PREFIX + match.group(0)[1:]

    return _RISK_ID_RE.sub(swap, text)


def finalize_strategy(strategy: str, effort_data, risk_register: str) -> str:
    """Post-processing every Strategy path applies after sanitizing."""
    strategy = relabel_unknown_risk_ids(strategy, risk_ledger(risk_register or ""))
    return drop_padding_references(enforce_effort_totals(strategy, effort_facts(effort_data)))


def finalize_test_plan(test_plan: str, risk_register: str) -> str:
    """Post-processing every Test Plan path applies after sanitizing."""
    return drop_padding_references(remove_unknown_risk_ids(test_plan, risk_ledger(risk_register or "")))
